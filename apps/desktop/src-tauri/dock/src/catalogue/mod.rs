/// One launchable app, as the shell knows it. Serialised into the catalogue cache.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct AppEntry {
    /// Stable id: the AppUserModelID when there is one, else the normalised target path.
    pub id: String,
    pub name: String,
    pub publisher: Option<String>,
    /// The explicit AppUserModelID the app's windows carry (never one the shell invented).
    pub aumid: Option<String>,
    /// The item's name inside `shell:AppsFolder`, explicit or invented; it launches the app like Start does.
    pub shell_id: Option<String>,
    /// Resolved target of the Start menu shortcut, in the case the shortcut stores it.
    pub target: Option<String>,
    pub arguments: Option<String>,
    /// The Start menu `.lnk`, preferred for launching because it keeps arguments and working directory.
    pub shortcut: Option<PathBuf>,
    /// First folder under Start menu `Programs` (`JetBrains`, `Windows System`...), a good category hint.
    pub folder: Option<String>,
    /// The icon file the shortcut names for itself, when that file exists; absent when the shortcut just
    /// shows its target's icon.
    pub icon_file: Option<PathBuf>,
    /// Install folder of a packaged (Store) app.
    pub package_dir: Option<PathBuf>,
}

impl AppEntry {
    pub fn packaged(&self) -> bool {
        self.package_dir.is_some()
    }

    /// Lower-case file name of the target (`code.exe`), which is what a running window is matched on.
    pub fn exe_name(&self) -> Option<String> {
        self.target.as_deref().filter(|t| !t.contains("://") && !t.starts_with("::")).and_then(file_name_lower)
    }

    /// What `ShellExecute` is given to start the app.
    pub fn launch_target(&self) -> Option<LaunchTarget> {
        if let Some(lnk) = &self.shortcut {
            return Some(LaunchTarget::Shortcut(lnk.clone()));
        }
        if let Some(id) = self.shell_id.as_ref().or(self.aumid.as_ref()) {
            return Some(LaunchTarget::AppsFolder(id.clone()));
        }
        self.target.as_ref().map(|t| LaunchTarget::Open(t.clone()))
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum LaunchTarget {
    Shortcut(PathBuf),
    /// `shell:AppsFolder\<id>`, the way Start launches an app.
    AppsFolder(String),
    /// A path or protocol URL (`steam://rungameid/...`) handed to the shell as is.
    Open(String),
}

impl LaunchTarget {
    /// The string `ShellExecute` takes.
    pub fn shell_path(&self) -> String {
        match self {
            LaunchTarget::Shortcut(p) => p.to_string_lossy().into_owned(),
            LaunchTarget::AppsFolder(id) => format!("shell:AppsFolder\\{id}"),
            LaunchTarget::Open(t) => t.clone(),
        }
    }
}

/// AppUserModelIDs the shell makes up for a shortcut that has none: `{KNOWN-FOLDER-GUID}\path.exe`,
/// `Microsoft.AutoGenerated.{GUID}`, a protocol URL or a plain path. They name the shortcut, not the running
/// app, so they are not used as an id.
pub fn is_synthetic_aumid(id: &str) -> bool {
    id.starts_with('{') || id.starts_with("Microsoft.AutoGenerated.") || id.contains("://") || id.contains(":\\")
}

/// The stable id of an app.
pub fn make_id(aumid: Option<&str>, target: Option<&str>, arguments: Option<&str>, shortcut: Option<&str>) -> String {
    if let Some(a) = aumid.map(str::trim).filter(|a| !a.is_empty()) {
        return a.to_owned();
    }
    if let Some(t) = target.map(str::trim).filter(|t| !t.is_empty()) {
        if t.contains("://") {
            return t.to_lowercase();
        }
        let args = arguments.map(str::trim).filter(|a| !a.is_empty());
        return match args {
            Some(a) => format!("{}?{}", normalise_path(t), a.to_lowercase()),
            None => normalise_path(t),
        };
    }
    format!("lnk:{}", normalise_path(shortcut.unwrap_or_default()))
}

/// Words that mark a shortcut as something other than an app: uninstallers, readmes, help, web links.
const NOISE_WORDS: [&str; 12] = [
    "uninstall",
    "uninstaller",
    "readme",
    "documentation",
    "manual",
    "license",
    "licence",
    "eula",
    "changelog",
    "website",
    "homepage",
    "help",
];
/// Phrases (in normalised-name form) with the same meaning.
const NOISE_PHRASES: [&str; 6] =
    ["release notes", "read me", "what s new", "getting started", "user guide", "quick start"];
/// First words that make a shortcut a link or an uninstaller ("Visit our website", "Remove Foo").
const NOISE_LEADING: [&str; 2] = [" visit ", " remove "];
/// Targets with these extensions are documents or links, not programs.
const DOCUMENT_EXTENSIONS: [&str; 12] =
    ["txt", "pdf", "html", "htm", "chm", "rtf", "md", "url", "doc", "docx", "xml", "log"];
/// Executable base names an uninstaller ships under.
const UNINSTALLER_EXE_PREFIXES: [&str; 3] = ["unins", "uninst", "uninstall"];

/// True for shortcuts that are not apps and must not reach the dock.
pub fn is_noise(name: &str, target: Option<&str>, arguments: Option<&str>) -> bool {
    let normalised = normalise_name(name);
    let padded = format!(" {normalised} ");
    if NOISE_WORDS.iter().any(|w| padded.contains(&format!(" {w} "))) {
        return true;
    }
    if NOISE_PHRASES.iter().any(|p| normalised.contains(p)) || NOISE_LEADING.iter().any(|w| padded.starts_with(w)) {
        return true;
    }
    if let Some(t) = target {
        let exe = file_name_lower(t).unwrap_or_default();
        let stem = exe.rsplit_once('.').map_or(exe.as_str(), |(s, _)| s);
        if UNINSTALLER_EXE_PREFIXES.iter().any(|p| stem.starts_with(p)) {
            return true;
        }
        if exe == "msiexec.exe" && arguments.is_some_and(|a| a.to_lowercase().contains("/x")) {
            return true;
        }
        if let Some((_, ext)) = exe.rsplit_once('.') {
            if DOCUMENT_EXTENSIONS.contains(&ext) {
                return true;
            }
        }
        if t.starts_with("http://") || t.starts_with("https://") {
            return true;
        }
    }
    false
}

fn merge_keys(entry: &AppEntry) -> Vec<String> {
    let mut keys = Vec::new();
    if let Some(a) = entry.aumid.as_deref() {
        keys.push(format!("aumid:{}", a.to_lowercase()));
        // One package listing the same name under two application ids (a front door and a settings door) is
        // one entry for the user.
        if entry.package_dir.is_some() {
            let family = a.split('!').next().unwrap_or(a).to_lowercase();
            keys.push(format!("package:{family}|{}", normalise_name(&entry.name)));
        }
    }
    if let Some(t) = entry.target.as_deref() {
        let args = entry.arguments.as_deref().map(str::trim).unwrap_or_default().to_lowercase();
        keys.push(format!("target:{}|{}", normalise_path(t), args));
        // Two shortcuts with one name and one program are one app, whatever arguments they pass.
        keys.push(format!("named:{}|{}", normalise_name(&entry.name), normalise_path(t)));
    }
    keys
}

/// Fills what `base` lacks from `extra` (both describe the same app).
fn absorb(base: &mut AppEntry, extra: AppEntry) {
    if base.publisher.is_none() {
        base.publisher = extra.publisher;
    }
    if base.aumid.is_none() {
        base.aumid = extra.aumid;
    }
    if base.shell_id.is_none() {
        base.shell_id = extra.shell_id;
    }
    if base.target.is_none() {
        base.target = extra.target;
        base.arguments = extra.arguments;
    }
    if base.shortcut.is_none() {
        base.shortcut = extra.shortcut;
    }
    if base.folder.is_none() {
        base.folder = extra.folder;
    }
    if base.icon_file.is_none() {
        base.icon_file = extra.icon_file;
    }
    if base.package_dir.is_none() {
        base.package_dir = extra.package_dir;
    }
}

/// Merges entries that describe one app (same AppUserModelID, or same target and arguments), keeps the first
/// name seen, drops noise, assigns ids and sorts by name. Candidates should be given Start menu first, so the
/// shortcut's name and launch path win over the AppsFolder duplicate.
pub fn merge(candidates: Vec<AppEntry>) -> Vec<AppEntry> {
    let mut merged: Vec<AppEntry> = Vec::new();
    let mut by_key: HashMap<String, usize> = HashMap::new();
    for candidate in candidates {
        if is_noise(&candidate.name, candidate.target.as_deref(), candidate.arguments.as_deref()) {
            continue;
        }
        let keys = merge_keys(&candidate);
        let hit = keys.iter().find_map(|k| by_key.get(k).copied());
        let index = match hit {
            Some(i) => {
                absorb(&mut merged[i], candidate);
                i
            }
            None => {
                merged.push(candidate);
                merged.len() - 1
            }
        };
        // Index every key the merged entry now has, so a later duplicate is found by any of them.
        for key in merge_keys(&merged[index]).into_iter().chain(keys) {
            by_key.insert(key, index);
        }
    }
    for entry in &mut merged {
        entry.id = make_id(
            entry.aumid.as_deref(),
            entry.target.as_deref(),
            entry.arguments.as_deref(),
            entry.shortcut.as_deref().map(|p| p.to_string_lossy()).as_deref(),
        );
    }
    merged.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()).then_with(|| a.id.cmp(&b.id)));
    merged.dedup_by(|b, a| a.id == b.id);
    merged
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(name: &str, target: Option<&str>) -> AppEntry {
        AppEntry { name: name.into(), target: target.map(str::to_owned), ..AppEntry::default() }
    }

    #[test]
    fn noise_is_dropped() {
        let cases = [
            ("Uninstall Foo", None, true),
            ("Foo Uninstaller", None, true),
            ("Foo Readme", None, true),
            ("README", None, true),
            ("Foo Help", None, true),
            ("Get Help", None, true),
            ("Release Notes", None, true),
            ("Visit Foo Website", None, true),
            ("Remove Foo", None, true),
            ("Foo", Some("C:\\Foo\\unins000.exe"), true),
            ("Foo", Some("C:\\Foo\\Uninstall.exe"), true),
            ("Foo", Some("C:\\Foo\\manual.pdf"), true),
            ("Foo", Some("C:\\Foo\\readme.txt"), true),
            ("Foo", Some("https://foo.example"), true),
            ("Visual Studio Code", Some("C:\\Code\\Code.exe"), false),
            ("Helpdesk Pro", Some("C:\\Helpdesk\\hd.exe"), false),
            ("Notepad++", Some("C:\\Notepad++\\notepad++.exe"), false),
            ("Remote Desktop Connection", Some("C:\\Windows\\system32\\mstsc.exe"), false),
            ("Calculator", None, false),
            ("Wordpad", None, false),
        ];
        for (name, target, noise) in cases {
            assert_eq!(is_noise(name, target, None), noise, "{name} {target:?}");
        }
    }

    #[test]
    fn msi_uninstall_shortcuts_are_noise() {
        assert!(is_noise("Foo", Some("C:\\Windows\\System32\\msiexec.exe"), Some("/x {GUID}")));
        assert!(!is_noise("Foo", Some("C:\\Windows\\System32\\msiexec.exe"), Some("/i foo.msi")));
    }

    #[test]
    fn ids_prefer_aumid_then_target_then_shortcut() {
        assert_eq!(make_id(Some("Chrome"), Some("C:\\x.exe"), None, None), "Chrome");
        assert_eq!(make_id(None, Some("C:/Apps/X.EXE"), None, None), "c:\\apps\\x.exe");
        assert_eq!(make_id(None, Some("C:\\Apps\\X.exe"), Some(" --app "), None), "c:\\apps\\x.exe?--app");
        assert_eq!(make_id(None, None, None, Some("C:\\Menu\\Foo.LNK")), "lnk:c:\\menu\\foo.lnk");
    }

    #[test]
    fn same_target_is_merged_and_start_menu_wins() {
        let mut a = entry("Foo", Some("C:\\Foo\\foo.exe"));
        a.shortcut = Some("C:\\Menu\\Foo.lnk".into());
        let mut b = entry("Foo", Some("c:\\foo\\FOO.exe"));
        b.shortcut = Some("C:\\Other\\Foo.lnk".into());
        let merged = merge(vec![a, b]);
        assert_eq!(merged.len(), 1);
        assert_eq!(merged[0].shortcut.as_deref(), Some(std::path::Path::new("C:\\Menu\\Foo.lnk")));
        assert_eq!(merged[0].id, "c:\\foo\\foo.exe");
    }

    #[test]
    fn same_target_different_arguments_stay_apart() {
        let mut a = entry("Foo App One", Some("C:\\Foo\\proxy.exe"));
        a.arguments = Some("--app-id=one".into());
        let mut b = entry("Foo App Two", Some("C:\\Foo\\proxy.exe"));
        b.arguments = Some("--app-id=two".into());
        assert_eq!(merge(vec![a, b]).len(), 2);
    }

    #[test]
    fn appsfolder_duplicate_merges_by_aumid_and_adds_package() {
        let mut start = entry("Foo", Some("C:\\Foo\\foo.exe"));
        start.aumid = Some("Foo.App".into());
        start.shortcut = Some("C:\\Menu\\Foo.lnk".into());
        let mut shell = entry("Foo", None);
        shell.aumid = Some("foo.app".into());
        shell.publisher = Some("Foo Inc".into());
        let merged = merge(vec![start, shell]);
        assert_eq!(merged.len(), 1);
        assert_eq!(merged[0].publisher.as_deref(), Some("Foo Inc"));
        assert_eq!(merged[0].id, "Foo.App");
    }

    #[test]
    fn appsfolder_item_merges_into_shortcut_by_resolved_target() {
        let mut start = entry("Notepad++", Some("C:\\Program Files\\Notepad++\\notepad++.exe"));
        start.shortcut = Some("C:\\Menu\\Notepad++.lnk".into());
        let mut shell = entry("Notepad++", Some("c:\\program files\\notepad++\\notepad++.exe"));
        shell.aumid = Some("{GUID}\\Notepad++\\notepad++.exe".into());
        let merged = merge(vec![start, shell]);
        assert_eq!(merged.len(), 1);
        assert!(merged[0].shortcut.is_some());
        assert_eq!(merged[0].aumid.as_deref(), Some("{GUID}\\Notepad++\\notepad++.exe"));
    }

    #[test]
    fn result_is_sorted_by_name_and_has_unique_ids() {
        let merged = merge(vec![entry("zeta", Some("C:\\z.exe")), entry("Alpha", Some("C:\\a.exe"))]);
        let names: Vec<_> = merged.iter().map(|e| e.name.as_str()).collect();
        assert_eq!(names, ["Alpha", "zeta"]);
    }

    #[test]
    fn launch_target_prefers_the_shortcut() {
        let mut e = entry("Foo", None);
        e.aumid = Some("Foo!App".into());
        assert_eq!(e.launch_target().unwrap().shell_path(), "shell:AppsFolder\\Foo!App");
        e.shortcut = Some("C:\\Menu\\Foo.lnk".into());
        assert_eq!(e.launch_target().unwrap().shell_path(), "C:\\Menu\\Foo.lnk");
    }

    #[test]
    fn launch_target_falls_back_to_the_shell_id_then_the_target() {
        let mut e = entry("Game", Some("steam://rungameid/10"));
        assert_eq!(e.launch_target().unwrap().shell_path(), "steam://rungameid/10");
        e.shell_id = Some("{GUID}\\Foo\\foo.exe".into());
        assert_eq!(e.launch_target().unwrap().shell_path(), "shell:AppsFolder\\{GUID}\\Foo\\foo.exe");
    }

    #[test]
    fn invented_ids_are_not_aumids() {
        for synthetic in [
            "{6D809377-6AF0-444B-8957-A3773F02200E}\\7-Zip\\7zFM.exe",
            "Microsoft.AutoGenerated.{68869CEC-7013-FFB3-52D6-2449D54DEF7D}",
            "steam://rungameid/291550",
            "C:\\ProgramData\\CodeMeter\\Backup",
        ] {
            assert!(is_synthetic_aumid(synthetic), "{synthetic}");
        }
        for real in ["Chrome", "com.squirrel.Discord.Discord", "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"] {
            assert!(!is_synthetic_aumid(real), "{real}");
        }
    }

    #[test]
    fn url_targets_keep_their_slashes_in_the_id() {
        assert_eq!(make_id(None, Some("steam://rungameid/291550"), None, None), "steam://rungameid/291550");
    }

    #[test]
    fn one_name_and_one_program_is_one_app_whatever_the_arguments() {
        let mut a = entry("Discord", Some("C:\\D\\discord.exe"));
        a.shortcut = Some("C:\\Menu\\Discord.lnk".into());
        let mut b = entry("Discord", Some("C:\\D\\discord.exe"));
        b.arguments = Some("--processStart Discord.exe".into());
        b.shortcut = Some("C:\\Menu\\Discord Inc\\Discord.lnk".into());
        assert_eq!(merge(vec![a, b]).len(), 1);
    }

    #[test]
    fn one_package_listing_a_name_twice_is_one_app() {
        let mut a = entry("Family", None);
        a.aumid = Some("Microsoft.Family_8wekyb3d8bbwe!App".into());
        a.package_dir = Some("C:\\WindowsApps\\Family".into());
        let mut b = entry("Family", None);
        b.aumid = Some("Microsoft.Family_8wekyb3d8bbwe!Family".into());
        b.package_dir = Some("C:\\WindowsApps\\Family".into());
        let mut c = entry("Family Settings", None);
        c.aumid = Some("Microsoft.Family_8wekyb3d8bbwe!Settings".into());
        c.package_dir = Some("C:\\WindowsApps\\Family".into());
        assert_eq!(merge(vec![a, b, c]).len(), 2);
    }
}
