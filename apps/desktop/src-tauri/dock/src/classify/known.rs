//! The bundled, reviewed table of well-known apps. Each entry lists how an app is recognised:
//!
//! - `name:` the normalised app name (lower case, words separated by single spaces). A trailing `*` means
//!   "starts with these whole words": `name:jetbrains*` matches `jetbrains toolbox` but not `jetbrainsx`.
//! - `exe:` the file name of the program the shortcut starts (`chrome.exe`).
//! - `aumid:` a prefix of the AppUserModelID, lower case (`microsoft.windowscalculator_`).
//!
//! Categories are tried in the order of `TABLE`, so a more specific entry in an earlier category beats a
//! general one in a later category (GitHub Copilot is AI, GitHub Desktop is development).
//! Nothing here is fetched from the network; the table is reviewed by hand against real machines.

use crate::protocol::Builtin;

pub struct Group {
    pub category: Builtin,
    pub patterns: &'static [&'static str],
}

